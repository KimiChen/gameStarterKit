// Relocate module specifiers without rewriting string literals in UI logic.
function relocateLogic(sourceName, sourceText) {
const source = ts.createSourceFile(sourceName, sourceText,
    ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const transformed = ts.transform(source, [(context) => {
    const visit = (node) => {
        if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier)
            && node.moduleSpecifier.text.startsWith(".")) {
            const target = resolve(client, "src/ui-uniflex", node.moduleSpecifier.text);
            const path = relative(generated, target).replace(/\.js$/, "");
            return context.factory.updateImportDeclaration(node, node.modifiers,
                node.importClause, context.factory.createStringLiteral(
                    path.startsWith(".") ? path : `./${path}`), node.attributes);
        }
        return ts.visitEachChild(node, visit, context);
    };
    return (node) => ts.visitNode(node, visit);
}]);
const result = rewriteGeneratedSpecifiers(ts.createPrinter().printFile(transformed.transformed[0]));
transformed.dispose();
return result;
}
