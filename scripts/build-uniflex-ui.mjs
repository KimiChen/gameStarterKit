function rewriteGeneratedSpecifiers(source) {
    return source.replace(/(['"])(@uniflex\/[^'"]+)\1/g, (all, quote, spec) => {
        const next = GENERATED_SPECIFIERS[spec] ?? (spec.startsWith("@uniflex/core/")
            ? `../../lib/uniflex/mod/core/${spec.slice("@uniflex/core/".length)}`
            : null);
        if (!next) throw new Error(`Unhandled UniFlex specifier in generated UI: ${spec}`);
        return quote + next + quote;
    });
}

